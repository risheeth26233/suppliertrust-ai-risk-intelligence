import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {chromium} from '../frontend/node_modules/playwright/index.mjs';

const base=process.env.SUPPLIERTRUST_FRONTEND_URL||'http://127.0.0.1:5173';
const demoBase=process.env.SUPPLIERTRUST_DEMO_URL||'http://127.0.0.1:5174';
const out=new URL('../output/playwright/',import.meta.url);
const output=fileURLToPath(out);
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.PW_CHANNEL?{channel:process.env.PW_CHANNEL}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const dialogs=['Demo Analyst','Fixture is fictional; reviewed for workflow testing.'];
page.on('dialog',async d=>d.accept(d.type==='prompt'?dialogs.shift()||'Demo Analyst':''));
try{
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Your supplier landscape'}).waitFor();
  await page.getByRole('button',{name:'Add supplier'}).click();
  await page.getByLabel('Legal business name').fill('Fictional Example Trading Co');
  await page.getByLabel('Category',{exact:true}).fill('Manufacturing');
  await page.getByLabel('Country',{exact:true}).fill('India');
  await page.getByLabel('GSTIN / CIN or other identifier').fill('27AAPFU0939F1ZV');
  await page.getByRole('button',{name:/Save supplier/}).click();
  await page.getByRole('heading',{level:2,name:'Fictional Example Trading Co'}).waitFor();
  await page.getByText('GSTIN checksum valid').waitFor();
  await page.getByLabel('Source URL').last().fill('https://example.com/verification');
  await page.getByLabel('Reviewer').last().fill('Demo Analyst');
  await page.getByLabel('Evidence notes').fill('Fictional evidence for end-to-end testing.');
  await page.getByRole('button',{name:'Save evidence'}).click();
  await page.getByText('Evidence recorded',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Screen against Synthetic browser fixture'}).click();
  await page.getByText('Fictional Example Trading Co',{exact:true}).last().waitFor();
  await page.getByText('Synthetic name-match fixture awaiting review').waitFor();
  await page.getByRole('button',{name:'False positive'}).click();
  await page.getByRole('button',{name:'Save observation'}).waitFor();
  await page.getByLabel('Observation date').fill('2026-01-15');
  await page.getByLabel('Reviewer').first().fill('Demo Analyst');
  await page.getByLabel('On-time delivery %').fill('92');
  await page.getByLabel('Defect rate %').fill('2');
  await page.getByLabel('Source URL').first().fill('https://example.com/performance.csv');
  await page.getByLabel('Notes',{exact:true}).fill('Fictional delivery observation for testing.');
  await page.getByRole('button',{name:'Save observation'}).click();
  await page.getByText('Performance observation recorded').waitFor();
  await page.getByRole('heading',{name:'Recent activity'}).waitFor();
  await page.getByRole('button',{name:'Overview'}).click();
  await page.getByRole('heading',{name:'Your supplier landscape'}).waitFor();
  await page.getByText('Performance observation recorded',{exact:true}).waitFor({state:'hidden'});
  await page.screenshot({path:fileURLToPath(new URL('dashboard-desktop.png',out)),fullPage:true,animations:"disabled"});
  await page.getByRole('button',{name:/Fictional Example Trading Co/}).first().click();
  await page.getByRole('heading',{level:2,name:'Fictional Example Trading Co'}).waitFor();
  await page.screenshot({path:fileURLToPath(new URL('supplier-profile-desktop.png',out)),fullPage:true,animations:"disabled"});
  const download=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download report'}).click();
  assert.match((await download).suggestedFilename(),/supplier-\d+-report\.txt/);
  await page.getByRole('button',{name:'Edit details'}).click();
  await page.getByLabel('Legal business name').fill('Fictional Northstar Trading Co');
  await page.getByRole('button',{name:/Save supplier/}).click();
  await page.getByRole('heading',{level:2,name:'Fictional Northstar Trading Co'}).waitFor();
  await page.getByRole('button',{name:/Suppliers/}).click();
  await page.getByRole('textbox',{name:'Search suppliers'}).fill('Northstar');
  await page.getByRole('button',{name:/Fictional Northstar Trading Co/}).first().waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:fileURLToPath(new URL('supplier-directory-mobile.png',out)),fullPage:true,animations:"disabled"});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'mobile layout has horizontal overflow');
  await page.getByRole('button',{name:/Fictional Northstar Trading Co/}).first().click();
  await page.getByRole('heading',{level:2,name:'Fictional Northstar Trading Co'}).waitFor();
  await page.getByRole('button',{name:'Delete supplier'}).click();
  await page.getByText('No suppliers yet',{exact:true}).waitFor();
  assert.deepEqual(errors,[],'browser reported uncaught JavaScript errors');
  const demo=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
  const demoErrors=[];
  demo.on('pageerror',e=>demoErrors.push(e.message));
  await demo.goto(demoBase,{waitUntil:'domcontentloaded'});
  await demo.getByRole('status').filter({hasText:'READ ONLY'}).waitFor();
  await demo.getByRole('button',{name:/Northstar Components Ltd/}).first().click();
  await demo.getByRole('heading',{level:2,name:'Northstar Components Ltd. (Fictional)'}).waitFor();
  await demo.getByRole('heading',{name:'Synthetic screening example'}).waitFor();
  for(const name of ['Add supplier','Edit details','Save evidence','Save observation','Refresh official OFAC dataset','Delete supplier','False positive']) assert.equal(await demo.getByRole('button',{name,exact:true}).count(),0,`${name} must be disabled in the public demo`);
  assert.equal(await demo.locator('input[type=file]').count(),0,'public demo must not expose uploads');
  assert.equal(await demo.getByText('Choose PDF',{exact:true}).count(),0,'public demo must not expose upload controls');
  await demo.screenshot({path:fileURLToPath(new URL('public-demo-profile.png',out)),fullPage:true,animations:"disabled"});
  await demo.setViewportSize({width:390,height:844});
  await demo.screenshot({path:fileURLToPath(new URL('public-demo-mobile.png',out)),fullPage:true,animations:"disabled"});
  assert.ok(await demo.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'public demo has horizontal overflow on mobile');
  assert.deepEqual(demoErrors,[],'public demo reported uncaught JavaScript errors');
  await demo.close();
  console.log('Browser workflow passed; screenshots saved to output/playwright.');
}finally{await browser.close();}
